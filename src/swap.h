/*
 * 四种交换写法 —— 它们是同一个格式的三次代入，不是三个技巧。
 *
 *     a ← f(a, b)
 *     b ← f⁻¹(a, b)
 *     a ← f⁻¹(a, b)
 *
 *     加减：f = a+b，f⁻¹ = a−b
 *     乘除：f = a×b，f⁻¹ = a÷b
 *     异或：f = a^b，f⁻¹ = a^b      ← 自己是自己的逆
 *
 * 成立的前提只有一个：**a 和 b 必须是两个互相独立的值**。
 * 这个前提在指针参数上很容易被违反（见 swap_xor 的注释），
 * 一旦违反，前三种写法全都会出错。
 */
#ifndef SWAP_H
#define SWAP_H

/*
 * 全部返回 void，但前三种在前提被破坏时会静默算错。
 * 需要检查时用 swap_selftest()，或者自己比较交换前后的值。
 */

/* 中间变量。任何时候都对，也是实际写代码应该用的那一种 */
void swap_tmp(int *a, int *b);

/* 加减法。溢出时在补码机器上仍然正确，但那是有符号溢出（UB） */
void swap_add(int *a, int *b);

/* 乘除法。除法代价高，而且 b 为 0 时直接崩，溢出面也更大 */
void swap_mul(int *a, int *b);

/*
 * 异或法。**只对整数有效**（浮点的存储方式做不了位运算），
 * 而且 a 与 b 指向同一处时会把值清零——第一行退化成 x ^ x = 0。
 */
void swap_xor(int *a, int *b);

/*
 * 用若干组值把四种写法都跑一遍，返回失败次数。
 *
 * 每组值都会额外测一次「两个指针指向同一个对象」——
 * 那是本仓库唯一会稳定复现的失败场景。
 */
int swap_selftest(void);

#endif /* SWAP_H */
